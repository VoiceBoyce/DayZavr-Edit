// INT_Quests — UI sounds of the «ПОЛЕВОЙ ДНЕВНИК» GUI. Paste into INT_Quests_CL\config.cpp.
// Generated by tools\gen_qst_sfx.py (do not edit by hand: change VOLUMES there and re-run).
// All sets are 2D UI sounds (spatial = 0, doppler = 0, loop = 0); play them on the client only, the way
// INT_BaseBoxAuthorization does (INT_BBA_Look.c): new SoundParams("INT_QST_Click_SoundSet") -> IsValid()
// -> SoundObjectBuilder(params).BuildSoundObject() -> so.SetKind(WaveKind.WAVEUI)
// -> GetGame().GetSoundScene().Play2D(so, builder).
//
// Levels: every file is normalized to the same K-weighted 200 ms loudness (-16 LK ~ LUFS short-term), peak
// <= -3 dBFS (short ticks are peak-limited and quieter). Base volume 0.7; the frequent / rustly ones sit
// a little lower. Resulting mix (file loudness + 20*log10(volume)):
//   int_qst_open       volume 0.60  ->  -20.6   (journal / giver window opens)
//   int_qst_close      volume 0.60  ->  -21.3   (window closes)
//   int_qst_page       volume 0.50  ->  -22.3   (tab switch, page change)
//   int_qst_click      volume 0.80  ->  -29.5   (buttons, rows, chips)
//   int_qst_stamp      volume 0.70  ->  -21.9   (quest accepted)
//   int_qst_check      volume 0.60  ->  -20.7   (objective done)
//   int_qst_complete   volume 0.70  ->  -19.6   (quest turned in)
//   int_qst_fail       volume 0.60  ->  -21.3   (quest failed / expired / abandoned)
//   int_qst_notify     volume 0.50  ->  -22.1   (banner slides in)
//   int_qst_pin        volume 0.80  ->  -30.4   (track toggle / pin)
//   int_qst_error      volume 0.55  ->  -23.6   (action refused)

