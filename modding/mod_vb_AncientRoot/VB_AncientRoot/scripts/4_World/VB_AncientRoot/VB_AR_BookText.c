			case VB_AR_Favor.TIER_FRIEND:
				return "Лес поет тебе навстречу. Стражи не тронут тебя первыми, роща дарит больше пыльцы, а ее Благословение держится час.";
			case VB_AR_Favor.TIER_OWN:
				return "Лес тебя знает. Стражи не нападут первыми, пока ты не обидишь рощу.";
			case VB_AR_Favor.TIER_ENEMY:
				return "Лес насторожен. Ночью в чаще за тобой могут выйти волки.";
			case VB_AR_Favor.TIER_CURSED:
