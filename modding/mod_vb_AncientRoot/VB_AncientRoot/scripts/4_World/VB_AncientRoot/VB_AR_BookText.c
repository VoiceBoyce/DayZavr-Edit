	// ступень, с которой открывается страница, — в творительном падеже: «назовет тебя Своим»
	static string VB_NeedWord(int tier)
	{
		if (tier >= VB_AR_Favor.TIER_FRIEND)
			return "Другом леса";
		return "Своим";
	}

	static int VB_NeedValue(int tier)
	{
		if (tier >= VB_AR_Favor.TIER_FRIEND)
			return VB_AR_Favor.FRIEND_FROM;
		return VB_AR_Favor.OWN_FROM;
	}

