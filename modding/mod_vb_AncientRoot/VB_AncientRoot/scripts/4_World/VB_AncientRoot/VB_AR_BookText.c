// «Книга древних» — страницы и главы (ТЗ_сервер_18.md, ветка 2в; решения пользователя 2026-11-16). Только клиент.
// Каждая пара страниц — разворот; закладки ведут к первой странице главы. Разметка текста: [слово] — выделено цветом
// (VB_AR_BookText.VB_Ink). Страница с Need выше «Чужака» читается только с этой ступени расположения: ниже неё вместо
// текста руническая вязь и подсказка, что нужно (так игрок узнаёт, что книга открывается по расположению).
// Объём: страница с картинкой — до ~500 знаков, без картинки — до ~950, заметка на полях — до ~160, запись изделия — до ~260.
// Числа в тексте — как в ГАЙД.md (раздел «Механики»); поменялись настройки — поправить и здесь.

class VB_AR_BookPage
{
	static const int KIND_TEXT = 0;
	static const int KIND_ITEMS = 1;		// две записи с картинками (каталог изделий)
	static const int KIND_YOU = 2;			// «Ты и лес»: ступень, ветвь, что открыто

	int Kind;
	string Title;
	string Pic;			// класс предмета для картинки ("" — без картинки)
	string Body;
	string Note;		// заметка на полях
	int Need = -2;		// с какой ступени расположения страница читается (-2 = VB_AR_Favor.TIER_CURSED — всем)
	string Pic1;
	string Name1;
	string Text1;
	string Pic2;
	string Name2;
	string Text2;
}

class VB_AR_BookChapter
{
	string Tab;
	int Page;			// первая страница главы (с нуля, всегда левая)
	int Color;

	void VB_AR_BookChapter(string tab, int page, int color)
	{
		Tab = tab;
		Page = page;
		Color = color;
	}
}

