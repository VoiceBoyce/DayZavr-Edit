# ---------------------------------------------------------------------------------------------- цели и награды
def kill(cls, n, text, weapon="", zone="", radius=0.0):
    return dict(Kind="KILL", Target=cls, Count=float(n), Filter=weapon, ZoneCenter=zone, ZoneRadius=float(radius), Text=text)


def deliver(cls, n, text, worst="BADLY_DAMAGED", minq=0):
    return dict(Kind="DELIVER", Target=cls, Count=float(n), WorstState=worst, MinQuantity=minq, Text=text)


def search(cls, n, text):
    return dict(Kind="SEARCH", Target=cls, Count=float(n), WorstState="BADLY_DAMAGED", Text=text)


def action(name, n, text, target=""):
    return dict(Kind="ACTION", Target=name, Count=float(n), Filter=target, Text=text)


def explore(pos, text, radius=60.0):
    return dict(Kind="EXPLORE", Target="", Count=1.0, Position=pos, Radius=float(radius), GroundY=1, ShowOnMap=1, Text=text)


def fish(n, text):
    return dict(Kind="FISH", Target="Edible_Base", Count=float(n), Text=text)


def copper(n):
    return dict(Kind="ITEM", Item="DZVR_Coin_Copper", Count=n, State="PRISTINE", Text="Медная монета")


def silver(n):
    return dict(Kind="ITEM", Item="DZVR_Coin_Silver", Count=n, State="PRISTINE", Text="Серебряная монета")


def gold(n):
    return dict(Kind="ITEM", Item="DZVR_Coin_Gold", Count=n, State="PRISTINE", Text="Золотая монета")


def item(cls, text, n=1, qty=""):
    return dict(Kind="ITEM", Item=cls, Count=n, Quantity=qty, State="", Text=text)


def stack(cls, n, text):
    return item(cls, text + " ×%d" % n, 1, str(n))


class Q:
    def __init__(self, qid, branch, order, name, start, finish, text, targets, rewards, requires=(), any_=0,
                 repeat="ONCE", time_limit=0, quest_items=(), code="", cooldown=0, groves=False):
        self.Id, self.branch, self.Order, self.Name = qid, branch, order, name
        self.GiverStart, self.GiverFinish, self.text = start, finish, text
        self.Targets, self.Rewards = list(targets), list(rewards)
        self.Requires, self.RequireAny = list(requires), any_
        self.RepeatMode, self.TimeLimit, self.Cooldown = repeat, time_limit, cooldown
        self.QuestItems = [dict(Item=c, Count=n) for c, n in quest_items]
        self.code = code
        self.groves = groves or branch == "C_VOLHV"     # нужны рощи «Древнего корня»


def enabled(q):
    return 1 if (GROVES_ON or not q.groves) else 0


