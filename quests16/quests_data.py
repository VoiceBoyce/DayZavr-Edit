def mat_reward(key, n):
    return stack("VB_AB_Mat_" + key, n, MAT[key])


def element_reward(element, total):
    """total материалов стихии, по кругу по списку стихии, стопками."""
    keys = ELEMENT_MATS[element]
    cnt = {}
    for i in range(total):
        k = keys[i % len(keys)]
        cnt[k] = cnt.get(k, 0) + 1
    return [mat_reward(k, n) for k, n in cnt.items()]


